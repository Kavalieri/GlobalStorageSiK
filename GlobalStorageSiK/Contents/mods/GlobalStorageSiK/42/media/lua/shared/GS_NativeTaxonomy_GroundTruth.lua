	dev24 (pedido explicito de sistemas, DEV24 - "infraestructura de corpus
	ground-truth"): manifiesto DECLARATIVO y VERSIONADO de casos esperados,
	separado por completo del clasificador - GS_NativeCorpus.lua (el runner)
	NUNCA genera estos datos automaticamente a partir de la salida actual del
	clasificador, eso convertiria los fallos existentes en expectativas.
	Desarrollo aporta este esquema/fichero y el runner; Sistemas/QA aporta o
	aprueba las expectativas concretas.

	Corpus PILOTO de dev24 - pequeño y verificable, pensado para probar el
	MECANISMO (runner, metricas, distincion required/optional/missing), NO
	para declarar maduros los 13 bloques L1. Amplíar el corpus es trabajo de
	una ronda posterior, tras cerrar la puerta QA de esta.

	Cada caso puede expresar:
	- caseId (string ASCII, unico y estable - identificador tecnico para el
	  log runtime, NUNCA depende de texto humano/notas; dev25, pedido
	  explicito de sistemas)
	- fullType (string, obligatorio)
	- block (string, agrupacion en el resumen - normalmente el L1 esperado)
	- presence: "required" | "optional" - que hacer si el fullType NO existe
	  en el catalogo real de esta partida (mod no instalado, item renombrado):
	  "required" -> el caso cuenta como FALLIDO; "optional" -> el caso cuenta
	  como OMITIDO (ni aprobado ni fallido), nunca como fallo.
	- expectAbstain: true si se espera que NINGUN bloque especifico reclame
	  el tipo (resultado final "other/unclassified_modded" honesto) - en vez
	  de expectedL1/L2/L3.
	- expectedL1/expectedL2/expectedL3: ruta esperada cuando expectAbstain
	  es false/nil. expectedL3 puede ser `false` explicito para decir "se
	  espera L3 vacio/nil" (nil normal de Lua en una tabla no se puede
	  distinguir de "campo ausente", de ahi el `false` explicito).
	- minConfidence: confianza minima esperada en evidence.primary.confidence
	  (numero|nil, sin comprobar si es nil).
	- expectedSource: fuente esperada en evidence.primary.source (string|nil).
	- expectFacets / expectAttributes: tablas clave->valor esperado, solo se
	  comprueban las claves presentes aqui (no exige que sean las UNICAS).
	- note: justificacion tecnica de por que la expectativa es ground-truth
	  (siempre con referencia a la ronda dev que la confirmo).
]]

